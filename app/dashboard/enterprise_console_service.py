from __future__ import annotations

from pathlib import Path
from typing import Any

from app.dashboard.dashboard_i18n import DashboardTranslator
from app.dashboard.dashboard_view_models import (
    DashboardPageModel,
    DownloadItem,
    EnterpriseConsoleModel,
    KpiCard,
    StatusBadge,
)
from app.services.dashboard_summary import DashboardSummaryService


class EnterpriseConsoleService:
    """Prepare UI view models for the QDKEP Enterprise Quality Console.

    The service is deliberately read-only. It delegates quality facts to
    DashboardSummaryService, which itself reads outputs generated by validators,
    package builder, gates, exporters, traceability and benchmark services.
    """

    PAGE_WORKFLOW_MAP: dict[str, str | None] = {
        "overview": None,
        "contract_validation": "contract_validation",
        "package_builder": None,
        "quality_gates": "package_quality_gate",
        "ai4biz_export": "ai4biz_export_readiness",
        "evidence_traceability": "traceability",
        "generators": "golden_questions_generation",
        "benchmark": "benchmark_readiness",
        "send_feedback": None,
        "reports_downloads": None,
        "settings": None,
    }

    def build_model(self, package_path: str | Path, language: str = "en") -> EnterpriseConsoleModel:
        translator = DashboardTranslator(language)
        summary = DashboardSummaryService().summarize(package_path)
        metrics = summary.get("metrics", {}) if isinstance(summary.get("metrics"), dict) else {}
        workflow = summary.get("workflow", {}) if isinstance(summary.get("workflow"), dict) else {}
        downloads = [
            DownloadItem(**item) for item in summary.get("downloads", []) if isinstance(item, dict)
        ]
        issues = [item for item in summary.get("issues", []) if isinstance(item, dict)]
        warnings = [str(item) for item in summary.get("warnings", [])]

        kpis = [
            KpiCard("status", summary.get("status", "unknown"), "Enterprise review status"),
            KpiCard(
                "promotion_decision",
                summary.get("promotion_decision", "unknown"),
                "Promotion gate output",
            ),
            KpiCard("artifact_count", metrics.get("artifact_count"), "Contract artifacts"),
            KpiCard("document_count", metrics.get("document_count"), "AI4BIZ export documents"),
            KpiCard(
                "metadata_file_count", metrics.get("metadata_file_count"), "AI4BIZ metadata files"
            ),
            KpiCard(
                "golden_questions.jsonl", metrics.get("golden_question_count"), "Golden questions"
            ),
        ]

        # Keep the overview focused on actionable workflow states. Retrieval and
        # answer readiness are intentionally not promoted as dashboard badges in
        # v2.0.5 because those checks belong to the target AI4BIZ/RAG platform
        # where index and answer traces actually exist. Traceability remains
        # visible once through the workflow report badge below.
        badges = [
            StatusBadge(
                "promotion_decision",
                str(summary.get("promotion_decision", "unknown")),
                self._tone(summary.get("promotion_decision")),
            ),
        ]
        for key, data in workflow.items():
            if isinstance(data, dict):
                badges.append(
                    StatusBadge(
                        key, str(data.get("status", "unknown")), self._tone(data.get("status"))
                    )
                )

        pages = self._pages(translator, summary, workflow, metrics, issues, warnings, downloads)
        return EnterpriseConsoleModel(
            status=str(summary.get("status", "unknown")),
            package_path=str(summary.get("package_path", package_path)),
            promotion_decision=str(summary.get("promotion_decision", "unknown")),
            kpis=kpis,
            badges=badges,
            pages=pages,
            issues=issues,
            warnings=warnings,
            downloads=downloads,
            raw_summary=summary,
        )

    def _pages(
        self,
        translator: DashboardTranslator,
        summary: dict[str, Any],
        workflow: dict[str, Any],
        metrics: dict[str, Any],
        issues: list[dict[str, Any]],
        warnings: list[str],
        downloads: list[DownloadItem],
    ) -> dict[str, DashboardPageModel]:
        pages: dict[str, DashboardPageModel] = {}
        for page_key, workflow_key in self.PAGE_WORKFLOW_MAP.items():
            workflow_data = workflow.get(workflow_key, {}) if workflow_key else {}
            page_issues = (
                issues
                if page_key in {"overview", "quality_gates", "reports_downloads"}
                else self._issues_for(page_key, issues)
            )
            page_warnings = (
                warnings
                if page_key in {"overview", "reports_downloads", "settings"}
                else self._warnings_for(page_key, warnings)
            )
            page_downloads = (
                downloads
                if page_key == "reports_downloads"
                else self._downloads_for(page_key, downloads)
            )
            pages[page_key] = DashboardPageModel(
                page_key=page_key,
                title=translator.text(page_key),
                status=str(workflow_data.get("status", summary.get("status", "unknown")))
                if isinstance(workflow_data, dict)
                else str(summary.get("status", "unknown")),
                summary=str(workflow_data.get("summary", translator.text("service_backed")))
                if isinstance(workflow_data, dict)
                else translator.text("service_backed"),
                source=str(workflow_data.get("source"))
                if isinstance(workflow_data, dict) and workflow_data.get("source")
                else None,
                metrics=metrics,
                issues=page_issues,
                warnings=page_warnings,
                downloads=page_downloads,
                raw=workflow_data if isinstance(workflow_data, dict) else {},
            )
        return pages

    def _tone(self, status: Any) -> str:
        value = str(status or "unknown").lower()
        if (
            value
            in {"approved", "success", "ready", "generated", "review_ready", "completed", "built"}
            or "approved" in value
        ):
            return "success"
        if (
            value in {"blocked", "error", "failed", "not_ready"}
            or "blocked" in value
            or "error" in value
        ):
            return "error"
        if value in {"missing", "partial_traceability", "not_evaluated", "unknown"}:
            return "warning"
        return "info"

    def _issues_for(self, page_key: str, issues: list[dict[str, Any]]) -> list[dict[str, Any]]:
        needles = {
            "contract_validation": ["contract", "metadata", "filename", "structure"],
            "package_builder": ["manifest", "package", "zip"],
            "quality_gates": ["customer", "interface", "promotion", "gate"],
            "ai4biz_export": ["ai4biz", "metadata", "document"],
            "evidence_traceability": ["traceability", "evidence", "source", "mpl"],
            "benchmark": ["benchmark", "retrieval", "answer", "golden"],
            "send_feedback": ["feedback", "remediation", "benchmark"],
            "generators": ["generator", "runbook", "kedb", "documentation"],
        }.get(page_key, [])
        if not needles:
            return []
        selected = []
        for issue in issues:
            text = " ".join(str(v).lower() for v in issue.values())
            if any(needle in text for needle in needles):
                selected.append(issue)
        return selected

    def _warnings_for(self, page_key: str, warnings: list[str]) -> list[str]:
        needles = {
            "contract_validation": ["contract", "metadata"],
            "quality_gates": ["gate", "promotion", "customer", "interface"],
            "qdkep_export": ["qdkep", "metadata"],
            "evidence_traceability": ["trace", "evidence", "mpl"],
            "benchmark": ["retrieval", "answer", "benchmark"],
            "send_feedback": ["feedback", "remediation", "benchmark"],
            "generators": ["generator", "runbook", "kedb", "doc"],
        }.get(page_key, [])
        if not needles:
            return []
        return [
            warning for warning in warnings if any(needle in warning.lower() for needle in needles)
        ]

    def _downloads_for(self, page_key: str, downloads: list[DownloadItem]) -> list[DownloadItem]:
        keys = {
            "contract_validation": {"contract_validation_report"},
            "package_builder": {"zip", "manifest", "package_metadata"},
            "quality_gates": {"package_quality_gate_report"},
            "qdkep_export": {"qdkep_ingestion_readiness_report"},
            "evidence_traceability": {"traceability_report"},
            "benchmark": {"benchmark_readiness_report", "golden_questions"},
            "send_feedback": {"feedback"},
            "generators": {"golden_questions"},
        }.get(page_key, set())
        return [item for item in downloads if item.key in keys]
